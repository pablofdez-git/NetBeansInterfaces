    private void btn_calcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_calcularActionPerformed
        Date fechaNacimiento = (Date) ftx_fechaNac.getValue();
        System.out.println(fechaNacimiento);
        
        LocalDate fechaActual = LocalDate.now();
        LocalDate fechaUser = fechaNacimiento.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
        
        int edad = (int) ChronoUnit.YEARS.between(fechaUser, fechaActual);
        
        lbl_edad.setText(Integer.toString(edad));
        
    }//GEN-LAST:event_btn_calcularActionPerformed

