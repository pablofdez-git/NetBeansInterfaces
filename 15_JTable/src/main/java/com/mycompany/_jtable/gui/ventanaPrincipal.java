    private void btn_anadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_anadirActionPerformed
        double nota1trim = Double.valueOf(txt_1trim.getText());
        double nota2trim = Double.valueOf(txt_2trim.getText());
        double nota3trim = Double.valueOf(txt_3trim.getText());
        double notaMedia = (nota1trim + nota2trim + nota3trim) /3;
        
        mt_notas.addRow(new Object[] {nota1trim, nota2trim, nota3trim, notaMedia});
        
        txt_1trim.setText("");
        txt_2trim.setText("");
        txt_3trim.setText("");
    }//GEN-LAST:event_btn_anadirActionPerformed

    private void btn_actualizarçActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_actualizarçActionPerformed
        double nota1trim = Double.valueOf(txt_1trim.getText());
        double nota2trim = Double.valueOf(txt_2trim.getText());
        double nota3trim = Double.valueOf(txt_3trim.getText());
        
        mt_notas.setValueAt(nota1trim,tb_notas.getSelectedRow(),0);
        mt_notas.setValueAt(nota2trim,tb_notas.getSelectedRow(),1);
        mt_notas.setValueAt(nota3trim,tb_notas.getSelectedRow(),2);
        
        double notaMedia = (nota1trim + nota2trim + nota3trim) /3;
        mt_notas.setValueAt(notaMedia, tb_notas.getSelectedRow(),3);
        
        txt_1trim.setText("");
        txt_2trim.setText("");
        txt_3trim.setText("");
    }//GEN-LAST:event_btn_actualizarçActionPerformed

    private void btn_borrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_borrarActionPerformed
        mt_notas.removeRow(tb_notas.getSelectedRow());
    }//GEN-LAST:event_btn_borrarActionPerformed

