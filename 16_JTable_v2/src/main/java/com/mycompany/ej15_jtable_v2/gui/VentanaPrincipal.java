    // Volcar la lista en la tabla
    private void refrescarTabla() {
        mt.setRowCount(0);                          // vacía la tabla
        for (NotasAlumno n : notas) {
            mt.addRow(n.toArrayString());           // una fila por objeto
        }
    }
    
    // Leer un campo aceptando como o punto decimial. Lanza NumberFormatException si no es válido. 
    private double leerNota(String texto) {
        return Double.parseDouble(texto.trim().replace(',', '.'));
    }
    
    // Comprobar si una nota es válida (esta entre 0 y 10)
    private boolean esNotaValida(double nota) {
        return nota >= 0 && nota <= 10;
    }
    
    // Limpiar los campos de introducción de datos
    private void limpiarCampos() {
        txt_nota1trim.setText("");
        txt_nota2trim.setText("");
        txt_nota3trim.setText("");
    }
    
