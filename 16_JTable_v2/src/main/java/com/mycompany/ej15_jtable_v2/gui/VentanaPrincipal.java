    private void btn_insertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_insertarActionPerformed
        try {
            double nota1trim = leerNota(txt_nota1trim.getText());
            double nota2trim = leerNota(txt_nota2trim.getText());
            double nota3trim = leerNota(txt_nota3trim.getText());
 
            if (!esNotaValida(nota1trim) || !esNotaValida(nota2trim) || !esNotaValida(nota3trim)) {
                JOptionPane.showMessageDialog(this, "Las notas deben estar entre 0 y 10.",
                        "Error de validación", JOptionPane.ERROR_MESSAGE);
                return;
            }
 
            double notaMedia = (nota1trim + nota2trim + nota3trim) / 3;
            notas.add(new NotasAlumno(nota1trim, nota2trim, nota3trim, notaMedia));   // 1º actualziar el modelo de datos
            refrescarTabla();                                                         // 2º actualziar la vista
            limpiarCampos();                                                          // limpiar campos introducción datos
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Introduce valores numéricos válidos en todos los campos.",
                    "Error de entrada", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_insertarActionPerformed

    private void btn_actualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_actualizarActionPerformed
        int fila = tbl_notas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una fila antes de actualizar.");
            return;
        }
 
        NotasAlumno alumno = notas.get(fila);       // Recupera de la lista el objeto que corresponde a la fila seleccionada en la tabla
        
        // Agrupar las tres cajas de texto en un array para recorrerlas con un bucle en vez de repetir código
        JTextField[] campos = {txt_nota1trim, txt_nota2trim, txt_nota3trim};
        
        // Crea un array con las notas actuales del alumno. Es el punto de partida: si el usuario deja una caja vacía, 
        //              esa nota se queda como estaba. Si escribe algo, el bucle sustituye esa posición por el valor nuevo.
        double[] nuevas = {alumno.getNota1trim(), alumno.getNota2trim(), alumno.getNota3trim()};
 
        try {
            for (int i = 0; i < 3; i++) {
                String texto = campos[i].getText().trim();    // recupera lo que hay en cada campo de texto ahora mismo
                if (!texto.isEmpty()) {                       // solo se cambia lo que se ha escrito
                    double valor = leerNota(texto);
                    if (!esNotaValida(valor)) {
                        JOptionPane.showMessageDialog(this, "Las notas deben estar entre 0 y 10.",
                                "Error de validación", JOptionPane.ERROR_MESSAGE);
                        return;                               // no se modifica nada si hay error
                    }
                    nuevas[i] = valor;
                }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Introduce valores numéricos válidos.",
                    "Error de entrada", JOptionPane.ERROR_MESSAGE);
            return;
        }
 
        // Todo es válido: actualziar el objeto y después la vista
        alumno.setNota1trim(nuevas[0]);
        alumno.setNota2trim(nuevas[1]);
        alumno.setNota3trim(nuevas[2]);
        alumno.setNotaMedia((nuevas[0] + nuevas[1] + nuevas[2]) / 3);
 
        refrescarTabla();
        tbl_notas.setRowSelectionInterval(fila, fila);           // mantiene la fila seleccionada
        limpiarCampos();
    }//GEN-LAST:event_btn_actualizarActionPerformed

    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        int fila = tbl_notas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una fila antes de borrar.");
            return;
        }
        notas.remove(fila);     // la posición en la tabla coincide con la posición en la lista
        refrescarTabla();
    }//GEN-LAST:event_btn_eliminarActionPerformed

    
