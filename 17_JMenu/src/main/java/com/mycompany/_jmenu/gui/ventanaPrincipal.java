    // Lee el contenido de un archivo txt
    private String leerArchivo(File archivo) {
        String contenido = "";
        try (BufferedReader b = new BufferedReader(new FileReader(archivo.getAbsolutePath()))) {
            String linea;
            while ((linea = b.readLine()) != null) {
                contenido += linea + "\n";
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(rootPane, "Error al leer el archivo: " + e.getMessage());
        }
        return contenido;
    }

    // Escribe un texto genérico en un archivo
    private boolean guardarArchivo(File archivo, String contenido) {
        try (FileWriter fw = new FileWriter(archivo.getAbsolutePath())) {
            fw.write(contenido);
            return true;
        } catch (IOException e) {
            JOptionPane.showMessageDialog(rootPane, "Error al guardar el archivo: " + e.getMessage());
            return false;
        }
    }
        
        
