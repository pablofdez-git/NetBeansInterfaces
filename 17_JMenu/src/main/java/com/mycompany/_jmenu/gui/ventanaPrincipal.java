    private void mni_abrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mni_abrirActionPerformed
        JFileChooser fc = new JFileChooser();
        fc.setFileSelectionMode(JFileChooser.FILES_ONLY);
        fc.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
        
        if(fc.showOpenDialog(rootPane) == JFileChooser.APPROVE_OPTION){
            nombreFichero = fc.getSelectedFile();
            
            String texto = leerArchivo(nombreFichero);
            jTextPane1.setText(texto);
        }
    }//GEN-LAST:event_mni_abrirActionPerformed

    private void mni_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mni_guardarActionPerformed
       if(nombreFichero == null){       //Si no hay archivo abierto pedir nombre
           JFileChooser fc = new JFileChooser();
           if(fc.showOpenDialog(rootPane) == JFileChooser.APPROVE_OPTION){
               nombreFichero = fc.getSelectedFile();
           }else{
               return;      // El usuario cancela en el selector de archivos
           }
       }
       
      if (guardarArchivo(nombreFichero, jTextPane1.getText())) {
           JOptionPane.showMessageDialog(rootPane, "Guardado Correcto");
       }
    }//GEN-LAST:event_mni_guardarActionPerformed

