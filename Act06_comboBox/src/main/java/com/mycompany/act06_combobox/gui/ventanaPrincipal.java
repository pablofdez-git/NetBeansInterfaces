    private void cmb_colorTextoItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmb_colorTextoItemStateChanged
        int indexSelected = cmb_colorTexto.getSelectedIndex();
        
        switch(indexSelected){
            case 0:
                lbl_colorFondo.setForeground(Color.WHITE);
                lbl_colorTexto.setForeground(Color.white);
                break;
            case 1:
                lbl_colorFondo.setForeground(Color.black);
                lbl_colorTexto.setForeground(Color.black);
                break;
            case 2:
                lbl_colorFondo.setForeground(Color.red);
                lbl_colorTexto.setForeground(Color.red);
                break;
            case 3:
                lbl_colorFondo.setForeground(Color.blue);
                lbl_colorTexto.setForeground(Color.blue);
                break;
                
        }
    }//GEN-LAST:event_cmb_colorTextoItemStateChanged

