    private void cmb_colorFondoItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmb_colorFondoItemStateChanged
       String seleccionado = (String) cmb_colorFondo.getSelectedItem();
       
       switch(seleccionado){
           case "Verde":
               pan_fondo.setBackground(Color.GREEN);
               break;
           case "Rojo":
               pan_fondo.setBackground(Color.RED);
               break;
           case "Azul":
               pan_fondo.setBackground(Color.BLUE);
               break;
           case "Amarillo":
               pan_fondo.setBackground(Color.YELLOW);
               break;
           case "Rosa":
               pan_fondo.setBackground(Color.PINK);
               break;
           case "Negro":
               pan_fondo.setBackground(Color.BLACK);
               break;
               
       }
    }//GEN-LAST:event_cmb_colorFondoItemStateChanged

