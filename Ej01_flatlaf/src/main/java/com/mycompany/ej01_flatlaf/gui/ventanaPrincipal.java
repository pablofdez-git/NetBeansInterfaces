    private void cb_selectorTemasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cb_selectorTemasActionPerformed
        String seleccionado = (String) cb_selectorTemas.getSelectedItem();
        try{
            switch (seleccionado) {
                case "FlatLightLaf":
                    UIManager.setLookAndFeel(new FlatLightLaf());
                    break;
                case "FlatMacLightLaf":
                    UIManager.setLookAndFeel(new FlatMacLightLaf());
                    break;
                case "FlatIntelliJLaf":
                    UIManager.setLookAndFeel(new FlatIntelliJLaf());
                    break;
                case "FlatDarculaLaf":
                    UIManager.setLookAndFeel(new FlatDarculaLaf());
                    break;
            } 
            SwingUtilities.updateComponentTreeUI(this);
        } catch (Exception ex) {
            ex.printStackTrace();
        } 
        
        
    }//GEN-LAST:event_cb_selectorTemasActionPerformed

