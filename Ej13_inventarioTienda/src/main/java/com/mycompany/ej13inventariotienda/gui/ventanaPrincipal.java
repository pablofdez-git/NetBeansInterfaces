    private void btn_anadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_anadirActionPerformed
        String nombre = txt_producto.getText();
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Introduce el nombre del producto.");
            return;
        }
        try {
            int cantidad = Integer.parseInt(txt_cantidad.getText());
            double precio = Double.parseDouble(txt_precio.getText().replace(',', '.'));
            if (cantidad<0 || precio<0) {
                JOptionPane.showMessageDialog(this, "Cantidad y precio no pueden ser negativos.");
                return;
            }
            productos.add(new ListaProductos(nombre, cantidad, precio));
            limpiarCampos();
            refrescarTabla();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Cantidad debe ser un entero y precio un número válido.");
        }
        
    }//GEN-LAST:event_btn_anadirActionPerformed

    private void btn_valorTotalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_valorTotalActionPerformed
        double total = 0;
        for (ListaProductos p : productos) {
            total += p.getCantidad() * p.getPrecio();
        }

        lbl_valorTotal.setText("Valor Total: " + total);
    }//GEN-LAST:event_btn_valorTotalActionPerformed

    private void btn_borrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_borrarActionPerformed
        int fila = tb_inventario.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una fila antes de borrar.");
            return;
        }
        productos.remove(fila);
        refrescarTabla();
    }//GEN-LAST:event_btn_borrarActionPerformed

    private void limpiarCampos() {
        txt_producto.setText("");
        txt_cantidad.setText("");
        txt_precio.setText("");
    }
    
    private void refrescarTabla() {
        mt.setRowCount(0);                          
        for (ListaProductos n : productos) {
            mt.addRow(n.toArrayString());
        }
    }
    
    
