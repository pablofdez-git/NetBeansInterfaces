    private void inicializarSpinnerFecha(){
        Date hoy = new Date();          // Crea un objeto date con la fecha actual
        SpinnerModel fechaModel = new SpinnerDateModel(hoy, null, null, Calendar.YEAR);     // Crea un modelo para el spinner
                                            // Empieza en hoy, no tiene fecha max ni min y al pasar las flechas se suma o resta años
        spn_fechaAlta.setModel(fechaModel);     // Asigna el modello al spinner
        spn_fechaAlta.setEditor(new JSpinner.DateEditor(spn_fechaAlta, "dd/MM/yyyy"));      // Define el formato visible de la fecha
    }

