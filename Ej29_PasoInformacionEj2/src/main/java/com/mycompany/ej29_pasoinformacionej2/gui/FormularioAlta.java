    private void btn_confirmarAltaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_confirmarAltaActionPerformed
        String nombre = txt_nombre.getText();
        String apellidos = txt_apellidos.getText();
        Date fechaAlta = (Date)spn_fechaAlta.getValue();
        String provincia = (String) cbx_provincia.getSelectedItem();
        Cliente c = new Cliente(nombre, apellidos, fechaAlta, provincia);
        GestionClientes.aniadirCliente(c);
        dispose();
    }//GEN-LAST:event_btn_confirmarAltaActionPerformed

