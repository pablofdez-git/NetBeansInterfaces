    // Método público para que el Controlador ordene pintar la tabla pasándole los datos.
    // El formateo de fecha (SimpleDateFormat) se hace aquí porque es una tarea visual.
    public void refrescarTabla(List<Cliente> listaClientes){         
        SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");   // Formateador de fecha para poder trabajar con ella como un String
        tm.setRowCount(0);      // Deja la tabla vacia para que se pueda volver a escribir toda la lista
                                // En sistemas mas avanzados se podrian hacer comparaciones internas y solo mandar pintar lo nuevo
                                
        for (Cliente c : listaClientes) {   // Pinta el cliente en la tabla formateando la fecha
            tm.addRow(new Object[]{
                c.getNombre(),
                c.getApellidos(),
                sdf.format(c.getFechaAlta()),
                c.getProvincia()
            });
        }
    }

