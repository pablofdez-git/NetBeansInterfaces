    private void btn_revivirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_revivirActionPerformed
        if (puntuacion > 10 && vida < 100) {
            vida = vida + 10;
            puntuacion = puntuacion - 10;
            pb_vida.setValue(vida);
            lbl_puntuacion.setText("Puntuación: " + puntuacion);
        } else {
            JOptionPane.showMessageDialog(this, "No se puede revivir", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btn_revivirActionPerformed

    private void btn_reanimarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_reanimarActionPerformed
        if (vida > 0) {
            vida = vida - 10;
            puntuacion = puntuacion + 10;
            pb_vida.setValue(vida);
            lbl_puntuacion.setText("Puntuación: " + puntuacion);

            if (vida == 0) {
                JOptionPane.showMessageDialog(this, "El pokémon ha muerto", "Game Over", JOptionPane.ERROR_MESSAGE);
                btn_revivir.setEnabled(false);
                btn_reanimar.setEnabled(false);
            }
        }
    }//GEN-LAST:event_btn_reanimarActionPerformed

