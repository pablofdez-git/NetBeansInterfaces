    private void cambiarTema() {
    try {
        if (com.formdev.flatlaf.FlatLaf.isLafDark()) {          // Comprueba si esta activo el tema oscuro.
            UIManager.setLookAndFeel(new FlatMacLightLaf());     // Si esta activo el oscuro pasa a claro
        } else {
            UIManager.setLookAndFeel(new FlatMacDarkLaf());    // Si esta activo el claro pasa al oscuro
        }
        SwingUtilities.updateComponentTreeUI(this);     // Repinta los componentes ya existentes con el nuevo tema
    } catch (Exception ex) {
        ex.printStackTrace();
    }
}

    
